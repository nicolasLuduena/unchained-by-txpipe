// Writes typed `as const` ABIs to src/lib/abi. The output is committed so the app builds without
// Foundry; rerun with `pnpm gen:abi` when an interface in contracts/src/interfaces changes.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const web = join(dirname(fileURLToPath(import.meta.url)), "..");
const contracts = join(web, "..", "contracts");
const out = join(web, "src", "lib", "abi");

const INTERFACES = [
  ["IHandoffRegistry", "handoffRegistryAbi"],
  ["IHandoffToken", "handoffTokenAbi"],
  ["IHandoffSettlement", "handoffSettlementAbi"],
];

const foundryForge = join(homedir(), ".config", ".foundry", "bin", "forge");
const forge = existsSync(foundryForge) ? foundryForge : "forge";

function inspect(name) {
  const stdout = execFileSync(forge, ["inspect", name, "abi", "--json"], {
    cwd: contracts,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "inherit"],
    maxBuffer: 16 * 1024 * 1024,
  });
  // forge can print compiler progress before the JSON.
  return JSON.parse(stdout.slice(stdout.indexOf("[")));
}

function fromArtifact(name) {
  return JSON.parse(readFileSync(join(contracts, "out", `${name}.sol`, `${name}.json`), "utf8")).abi;
}

function readAbi(name) {
  try {
    return inspect(name);
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
    console.warn(`gen-abi: forge not found, reading contracts/out for ${name}`);
    return fromArtifact(name);
  }
}

mkdirSync(out, { recursive: true });
for (const [name, exportName] of INTERFACES) {
  const abi = JSON.stringify(readAbi(name), null, 2);
  writeFileSync(
    join(out, `${name}.ts`),
    `// Generated by web/scripts/gen-abi.mjs from contracts/src/interfaces. Do not edit.\nexport const ${exportName} = ${abi} as const;\n`,
  );
}
writeFileSync(
  join(out, "index.ts"),
  [
    "// Generated by web/scripts/gen-abi.mjs. Do not edit.",
    ...INTERFACES.map(([name, exportName]) => `export { ${exportName} } from "./${name}";`),
    "",
  ].join("\n"),
);
console.log(`gen-abi: ${INTERFACES.length} interfaces`);
