// Turns design/ into something Next can import. Run by predev and prebuild; output is gitignored.
// design/ stays untouched: the bundle's IIFE runs unchanged against a module-local `window`,
// so it never touches the browser global and renders on the server as well.
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const web = join(dirname(fileURLToPath(import.meta.url)), "..");
const design = join(web, "..", "design");
const out = join(web, "src", "design", "generated");
const publicOut = join(web, "public", "design");

rmSync(out, { recursive: true, force: true });
rmSync(publicOut, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const bundle = readFileSync(join(design, "components", "bundle.js"), "utf8");
const header = bundle.match(/@ds-bundle: (\{.*\}) \*\//);
if (!header) throw new Error("design/components/bundle.js has no @ds-bundle header");
const names = JSON.parse(header[1]).components.map((c) => c.name);

// The local `window` only stands in for these two names. Anything else needs a real browser.
const globals = [...bundle.matchAll(/\b(?:window|document|globalThis)\b(?:\.\w+)?/g)].map((m) => m[0]);
const unexpected = globals.filter((g) => g !== "window.React" && g !== "window.Handoff");
if (unexpected.length) throw new Error(`bundle.js uses browser globals: ${unexpected.join(", ")}`);

writeFileSync(
  join(out, "handoff.js"),
  [
    '"use client";',
    "// Generated by web/scripts/sync-design.mjs from design/components/bundle.js. Do not edit.",
    'import * as React from "react";',
    "const window = { React };",
    bundle,
    ...names.map((name) => `export const ${name} = window.Handoff.${name};`),
    "",
  ].join("\n"),
);

// index.d.ts relies on the global JSX namespace, which React 19 types no longer declare.
const types = readFileSync(join(design, "components", "index.d.ts"), "utf8");
writeFileSync(join(out, "handoff.d.ts"), `import type { JSX } from "react";\n${types}`);

cpSync(join(design, "tokens.css"), join(out, "tokens.css"));
cpSync(join(design, "components", "bundle.css"), join(out, "components.css"));
cpSync(join(design, "fonts"), join(out, "fonts"), { recursive: true, filter: (src) => !src.endsWith("OFL.txt") });
cpSync(join(design, "logos"), join(publicOut, "logos"), { recursive: true, filter: (src) => !src.endsWith(".md") });

console.log(`sync-design: ${names.length} components`);
